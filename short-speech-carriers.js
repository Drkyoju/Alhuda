/** Short MC/TF speech carriers — display stays bare; TTS gets فصيح iʿrāb only.
 *  Shared by Azure Hamed lesson path and Fish bake/rollback scripts.
 *  Fidelity rule (v320): spoken bare words MUST equal written bare words.
 *  Allowed deltas: tashkeel / iʿrāb / NFC / allah-irab. No أعني… / paraphrases.
 *  (ه→هجرية is handled in prepareFishTtsText, not here.)
 */
/** Strip harakat/tatweel for whole-utterance carrier lookup. */
export function bareArabicKey(text) {
  return String(text || '')
    .replace(/[\u064B-\u065F\u0670\u0640]/g, '')
    .replace(/[^\u0621-\u064A\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

